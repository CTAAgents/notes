# ---------- 渲染器 ----------
def _para(doc, text, size=10.5, bold=False, italic=False, align="both", indent=True,
          cn=CN_BODY, en=EN_BODY, sb=0, sa=6, line=1.5, color=None):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = line
    pf.space_before = Pt(sb)
    pf.space_after = Pt(sa)
    p.alignment = {"both": WD_ALIGN_PARAGRAPH.JUSTIFY, "center": WD_ALIGN_PARAGRAPH.CENTER,
                   "left": WD_ALIGN_PARAGRAPH.LEFT}[align]
    if indent:
        pf.first_line_indent = Pt(size * 2)
    for i, seg in enumerate(text.split("**")):
        if not seg:
            continue
        r = p.add_run(seg)
        _font(r, cn=cn, en=en, size=size, bold=(bold or i % 2 == 1), italic=italic, color=color)
    return p


def _h(doc, text, level):
    sizes = {1: 16, 2: 13.5, 3: 12}
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(14 if level == 1 else 10)
    pf.space_after = Pt(8 if level == 1 else 6)
    pf.line_spacing = 1.3
    pf.keep_with_next = True
    r = p.add_run(text)
    _font(r, cn=CN_HEAD, en=EN_HEAD, size=sizes[level], bold=True)
    return p


def _bullet(doc, text, size=10.5):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = 1.5
    pf.space_after = Pt(3)
    pf.left_indent = Pt(21)
    pf.first_line_indent = Pt(-10.5)
    r = p.add_run("— " + text)
    _font(r, size=size)
    return p


def _cell(cell, text, size=9.5, bold=False, align="left"):
    cell.text = ""
    p = cell.paragraphs[0]
    p.paragraph_format.line_spacing = 1.15
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.space_before = Pt(2)
    if align == "center":
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    _font(r, size=size, bold=bold)


def _table(doc, headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, htxt in enumerate(headers):
        _cell(t.rows[0].cells[i], htxt, size=9.5, bold=True, align="center")
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            _cell(cells[i], str(v), size=9)
    if widths:
        for r_ in t.rows:
            for i, w in enumerate(widths):
                r_.cells[i].width = Cm(w)
    _para(doc, "", indent=False, sa=2)
    return t


def render(blocks):
    doc = Document()
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
    sec.left_margin = sec.right_margin = Cm(3.0)
    sec.top_margin = sec.bottom_margin = Cm(2.5)
    for kind, payload in blocks:
        if kind == "h1":
            _h(doc, payload, 1)
        elif kind == "h2":
            _h(doc, payload, 2)
        elif kind == "h3":
            _h(doc, payload, 3)
        elif kind == "p":
            _para(doc, payload)
        elif kind == "p_nc":
            _para(doc, payload, indent=False)
        elif kind == "p_nc_small":
            _para(doc, payload, indent=False, size=9.5, color=(90, 90, 90))
        elif kind == "p_nc_i":
            _para(doc, payload, indent=False, italic=True)
        elif kind == "center_big":
            _para(doc, payload, size=24, bold=True, align="center", indent=False,
                  cn=CN_HEAD, en=EN_HEAD, sa=10, sb=150)
        elif kind == "center_sub":
            _para(doc, payload, size=13.5, align="center", indent=False,
                  cn=CN_HEAD, en=EN_HEAD, sa=40)
        elif kind == "center_mid":
            _para(doc, payload, size=14, align="center", indent=False, sa=130)
        elif kind == "center_author":
            _para(doc, payload, size=12, align="center", indent=False)
        elif kind == "b":
            _bullet(doc, payload)
        elif kind == "ref":
            p = doc.add_paragraph()
            pf = p.paragraph_format
            pf.line_spacing = 1.35
            pf.space_after = Pt(3)
            pf.left_indent = Pt(24)
            pf.first_line_indent = Pt(-24)
            rr = p.add_run(payload)
            _font(rr, size=9.5)
        elif kind == "t":
            headers, rows, widths = payload
            _table(doc, headers, rows, widths)
        elif kind == "pb":
            doc.add_page_break()
    doc.save(OUT)
    print("SAVED", OUT)


