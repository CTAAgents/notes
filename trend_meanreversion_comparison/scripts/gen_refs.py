def _esc(s: str) -> str:
    """转义 LaTeX 特殊字符，并为长不可断词（arXiv 编号等）加断点。"""
    s = s.replace("&", r"\&").replace("_", r"\_").replace("%", r"\%").replace("#", r"\#")
    s = s.replace("arXiv:", r"arXiv:\allowbreak ")
    return s


def ev_tex() -> str:
    lines = [
        r"\section{证据表（核心来源逐条核验）}\label{sec:evidence}",
        "",
        r"下表收录本文引用的核心来源。\textbf{核验状态}约定：\textbf{已核验}=标题、作者、"
        r"年份、期刊卷期与 DOI 经 OpenAlex 或 Crossref 官方接口返回互证；"
        r"\textbf{部分核验}=专著或无 DOI 期刊，经出版页/馆藏/权威引用交叉确认；"
        r"\textbf{待复核}=仅能定位来源、具体书目细节需人工核对（正文避免依赖其数值）。"
        r"全部链接指向原始出处。",
        "",
        r"\begin{longtable}{@{}>{\raggedright\arraybackslash}p{2.55cm}>{\raggedright\arraybackslash}p{4.7cm}"
        r">{\raggedright\arraybackslash}p{2.7cm}>{\raggedright\arraybackslash}p{1.9cm}"
        r">{\raggedright\arraybackslash}p{1.45cm}@{}}",
        r"\caption{核心来源清单（共 %d 条）}\label{tab:evidence}\\ " % len(S),
        r"\toprule",
        r"\textbf{来源（作者，年）} & \textbf{标题} & \textbf{出处} & \textbf{链接} & \textbf{核验} \\",
        r"\midrule", r"\endfirsthead",
        r"\toprule \textbf{来源} & \textbf{标题} & \textbf{出处} & \textbf{链接} & \textbf{核验} \\ \midrule \endhead",
        r"\bottomrule \endlastfoot",
    ]
    for _, label, cat, title, author, venue, url, status in S:
        t = _esc(title)
        v = _esc(venue)
        a = _esc(author)
        lines.append(f"{a} & {t} & {v} & \\href{{{url}}}{{链接}} & {status} \\\\")
    lines += [r"\end{longtable}", ""]
    return "\n".join(lines)


def bib_tex() -> str:
    lines = [r"\section*{参考文献}", r"\addcontentsline{toc}{section}{参考文献}",
             r"\begin{thebibliography}{99}", r"\small"]
    for key, label, cat, title, author, venue, url, status in S:
        t = _esc(title)
        v = _esc(venue)
        a = _esc(author)
        lines.append(f"\\bibitem{{{key}}} {a}. \\emph{{{t}}}. {v}. "
                     f"\\href{{{url}}}{{{url}}}.")
    lines += [r"\end{thebibliography}"]
    return "\n".join(lines)


