CN_BODY, CN_HEAD = "宋体", "黑体"
EN_BODY, EN_HEAD = "Times New Roman", "Arial"


def _font(run, cn=CN_BODY, en=EN_BODY, size=10.5, bold=False, italic=False, color=None):
    run.font.name = en
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = RGBColor(*color)
    rpr = run._element.get_or_add_rPr()
    rf = rpr.find(qn("w:rFonts"))
    if rf is None:
        rf = OxmlElement("w:rFonts")
        rpr.append(rf)
    rf.set(qn("w:eastAsia"), cn)
    rf.set(qn("w:ascii"), en)
    rf.set(qn("w:hAnsi"), en)


def H1(t): return ("h1", t)
def H2(t): return ("h2", t)
def H3(t): return ("h3", t)
def P(t, indent=True): return ("p", t) if indent else ("p_nc", t)
def B(t): return ("b", t)
def T(h, r, w=None): return ("t", (h, r, w))
def PB(): return ("pb", None)

BLOCKS = []
def add(*items):
    BLOCKS.extend(items)


def _para(doc, text, size=10.5, bold=False, italic=False, align="both", indent=True,
          cn=CN_BODY, en=EN_BODY, sb=0, sa=4, line=1.4, color=None):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = line
    pf.space_before = Pt(sb)
    pf.space_after = Pt(sa)
    p.alignment = {"both": WD_ALIGN_PARAGRAPH.JUSTIFY, "center": WD_ALIGN_PARAGRAPH.CENTER,
                   "left": WD_ALIGN_PARAGRAPH.LEFT}[align]
    if indent:
        pf.first_line_indent = Pt(size * 2)
    for i, seg in enumerate(text.split("**")):
        if not seg:
            continue
        r = p.add_run(seg)
        _font(r, cn=cn, en=en, size=size, bold=(bold or i % 2 == 1), italic=italic, color=color)
    return p


def _h(doc, text, level):
    sizes = {1: 16, 2: 13.5, 3: 12}
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_before = Pt(20 if level == 1 else (10 if level == 2 else 7))
    pf.space_after = Pt(7 if level == 1 else (4.5 if level == 2 else 3.5))
    pf.line_spacing = 1.25
    pf.keep_with_next = True
    r = p.add_run(text)
    _font(r, cn=CN_HEAD, en=EN_HEAD, size=sizes[level], bold=True)
    return p


def _bullet(doc, text, size=10.5):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.line_spacing = 1.4
    pf.space_after = Pt(2.5)
    pf.left_indent = Pt(21)
    pf.first_line_indent = Pt(-10.5)
    r = p.add_run("— " + text)
    _font(r, size=size)
    return p


def _cell(cell, text, size=9.0, bold=False, align="left"):
    cell.text = ""
    p = cell.paragraphs[0]
    p.paragraph_format.line_spacing = 1.05
    p.paragraph_format.space_after = Pt(1.5)
    p.paragraph_format.space_before = Pt(1.5)
    if align == "center":
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    _font(r, size=size, bold=bold)


def _table(doc, headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, htxt in enumerate(headers):
        _cell(t.rows[0].cells[i], htxt, size=9.0, bold=True, align="center")
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            _cell(cells[i], str(v), size=8.5)
    if widths:
        for r_ in t.rows:
            for i, w in enumerate(widths):
                r_.cells[i].width = Cm(w)
    _para(doc, "", indent=False, sa=2)
    return t


def _footer_pagenum(section):
    """页脚居中页码（首页不显示）。"""
    section.different_first_page_header_footer = True
    p = section.footer.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    _font(run, size=9, color=(110, 110, 110))
    f1 = OxmlElement("w:fldChar"); f1.set(qn("w:fldCharType"), "begin")
    it = OxmlElement("w:instrText"); it.set(qn("xml:space"), "preserve"); it.text = "PAGE"
    f2 = OxmlElement("w:fldChar"); f2.set(qn("w:fldCharType"), "end")
    run._r.append(f1); run._r.append(it); run._r.append(f2)


def render(blocks):
    doc = Document()
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Cm(21.0), Cm(29.7)
    sec.left_margin = sec.right_margin = Cm(2.8)
    sec.top_margin = sec.bottom_margin = Cm(2.3)
    _footer_pagenum(sec)
    for kind, payload in blocks:
        if kind == "h1":
            _h(doc, payload, 1)
        elif kind == "h2":
            _h(doc, payload, 2)
        elif kind == "h3":
            _h(doc, payload, 3)
        elif kind == "p":
            _para(doc, payload)
        elif kind == "p_nc":
            _para(doc, payload, indent=False)
        elif kind == "p_nc_small":
            _para(doc, payload, indent=False, size=9.5,
                  color=(90, 90, 90)).paragraph_format.keep_with_next = True
        elif kind == "p_nc_i":
            _para(doc, payload, indent=False, italic=True)
        elif kind == "center_big":
            _para(doc, payload, size=22, bold=True, align="center", indent=False,
                  cn=CN_HEAD, en=EN_HEAD, sa=6, sb=18)
        elif kind == "center_sub":
            _para(doc, payload, size=12.5, align="center", indent=False,
                  cn=CN_HEAD, en=EN_HEAD, sa=10)
        elif kind == "center_mid":
            _para(doc, payload, size=12, align="center", indent=False, sa=12)
        elif kind == "center_author":
            _para(doc, payload, size=11, align="center", indent=False, sa=8)
        elif kind == "b":
            _bullet(doc, payload)
        elif kind == "ref":
            p = doc.add_paragraph()
            pf = p.paragraph_format
            pf.line_spacing = 1.35
            pf.space_after = Pt(3)
            pf.left_indent = Pt(24)
            pf.first_line_indent = Pt(-24)
            rr = p.add_run(payload)
            _font(rr, size=9.5)
        elif kind == "t":
            headers, rows, widths = payload
            _table(doc, headers, rows, widths)
        elif kind == "pb":
            doc.add_page_break()
    doc.save(OUT)
    print("SAVED", OUT)


